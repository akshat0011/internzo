#!/bin/bash
# Installs the LaunchAgent that keeps bin/loop.sh alive. The loop scans, waits
# out the rest of the interval (15 min by default) and repeats, forever.
#
#   bash bin/install-schedule.sh            install (refuses if the project sits
#                                           in a TCC-protected folder)
#   bash bin/install-schedule.sh --relocate move the project somewhere launchd
#                                           can read, then install
#   bash bin/install-schedule.sh --force    install anyway, TCC risk accepted
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_ID="linkedin-watcher"
LABEL="com.akshat0011.$APP_ID"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
SCRIPT_DIR="$HOME/Library/Application Scripts/$LABEL"
LOG_DIR="$HOME/Library/Logs/$APP_ID"
STATE_DIR="$HOME/Library/Application Support/$APP_ID"
TARGET_DIR="$STATE_DIR/app"
UID_NUM="$(id -u)"

MODE="${1:-}"

# ---------------------------------------------------------------------------
# TCC check. ~/Desktop, ~/Documents and ~/Downloads are protected folders. A
# launchd-spawned process is attributed to a bare interpreter with no stable
# code signature, so it gets no grant and cannot read the project — the tool
# works when you run it in Terminal and then silently fails at 12:00.
# ---------------------------------------------------------------------------
PROTECTED=""
case "$HERE" in
  "$HOME/Desktop"/*|"$HOME/Documents"/*|"$HOME/Downloads"/*) PROTECTED="yes" ;;
esac

if [ -n "$PROTECTED" ] && [ "$MODE" != "--force" ] && [ "$MODE" != "--relocate" ]; then
  cat <<EOF

  ┌─────────────────────────────────────────────────────────────────────┐
  │  Stopping before installing a schedule that would fail silently.    │
  └─────────────────────────────────────────────────────────────────────┘

  This project lives at:
      $HERE

  That is inside a macOS TCC-protected folder. Running it yourself in
  Terminal works, because Terminal already has permission. A job started by
  launchd does not — it runs as a bare interpreter with no stable identity,
  so at 12:00 it will either hit a permission prompt (which defeats the
  point of it being automatic) or fail with no visible error.

  Two ways forward:

  1. Move the project somewhere launchd can read it (recommended):

         bash bin/install-schedule.sh --relocate

     This moves the project to
         $TARGET_DIR
     and leaves a symlink behind at the current path, so
         cd $HERE
     keeps working exactly as it does now.

  2. Keep it on the Desktop and grant Full Disk Access to node by hand in
     System Settings > Privacy & Security > Full Disk Access. This is coarse
     — it authorises every script on the machine — and the grant may not
     stick, because macOS cannot pin an identity to a bare interpreter.
     If you want this, re-run with --force.

EOF
  exit 1
fi

if [ "$MODE" = "--relocate" ]; then
  if [ -z "$PROTECTED" ]; then
    echo "Project is already outside a protected folder — nothing to relocate."
  elif [ -e "$TARGET_DIR" ]; then
    echo "ERROR: $TARGET_DIR already exists. Move or remove it first." >&2
    exit 1
  else
    echo "Moving project:"
    echo "    from $HERE"
    echo "    to   $TARGET_DIR"
    mkdir -p "$(dirname "$TARGET_DIR")"
    # Copy first, verify, then swap — never leave the user without their files.
    cp -R "$HERE" "$TARGET_DIR"
    if [ ! -f "$TARGET_DIR/package.json" ]; then
      echo "ERROR: copy looks incomplete; leaving the original untouched." >&2
      rm -rf "$TARGET_DIR"
      exit 1
    fi
    ORIGINAL="$HERE"
    # Step out of the directory before deleting it. Your shell is almost
    # certainly sitting in it, and removing the cwd makes every later command
    # print "getcwd: cannot access parent directories".
    cd / || exit 1
    rm -rf "$ORIGINAL"
    ln -s "$TARGET_DIR" "$ORIGINAL"
    echo "Done. $ORIGINAL is now a symlink to the real location."
    echo "Re-running the installer from the new location…"
    exec bash "$TARGET_DIR/bin/install-schedule.sh"
  fi
fi

# ---------------------------------------------------------------------------
# Install
# ---------------------------------------------------------------------------

# launchd creates log FILES but never their parent directory; a missing
# directory makes the job fail to spawn at all.
mkdir -p "$HOME/Library/LaunchAgents" "$SCRIPT_DIR" "$LOG_DIR" "$STATE_DIR"

# The script launchd executes lives in ~/Library/Application Scripts, which is
# the location macOS intends for exactly this and is not TCC-protected.
cat > "$SCRIPT_DIR/run.sh" <<WRAPPER_EOF
#!/bin/bash
# Generated by install-schedule.sh — edit bin/loop.sh in the project instead.
# This starts the continuous scheduler, not a single run.
exec /bin/bash "$HERE/bin/loop.sh"
WRAPPER_EOF
chmod +x "$SCRIPT_DIR/run.sh" "$HERE/bin/run.sh" "$HERE/bin/loop.sh"

cat > "$PLIST" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>

    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>$SCRIPT_DIR/run.sh</string>
    </array>

    <key>WorkingDirectory</key>
    <string>$HERE</string>

    <!-- Not a schedule. bin/loop.sh is a single long-lived process that runs
         a scan, waits out the rest of the interval, and repeats forever, so
         launchd's only job here is to start it and keep it started.

         It used to be StartCalendarInterval at :00 and :30. Fixed clock slots
         have one bad property: a run that overruns its slot collides with the
         next one and the loser is skipped. At 15-minute slots that cost more
         than half the runs - 37 of 96 on one measured day, with 17.8 hours
         inside gaps over half an hour - because the lock was still held when
         the next slot fired. A loop has no slots to miss.

         RunAtLoad starts it at login; KeepAlive restarts it if it ever exits,
         so the loop is only stoppable by unloading the agent. -->
    <key>RunAtLoad</key>
    <true/>

    <key>KeepAlive</key>
    <true/>

    <!-- If the loop dies instantly and repeatedly, do not spin the CPU
         restarting it several times a second. -->
    <key>ThrottleInterval</key>
    <integer>30</integer>

    <!-- Only load in a logged-in GUI session; this job opens a browser. -->
    <key>LimitLoadToSessionType</key>
    <string>Aqua</string>

    <!-- The launchd default throttles CPU and I/O, which is wrong for a job
         whose whole purpose is driving a GUI browser. -->
    <key>ProcessType</key>
    <string>Interactive</string>

    <key>StandardOutPath</key>
    <string>$LOG_DIR/launchd.out.log</string>
    <key>StandardErrorPath</key>
    <string>$LOG_DIR/launchd.err.log</string>

    <!-- No shell expansion happens in a plist; every path must be literal. -->
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
        <key>HOME</key>
        <string>$HOME</string>
        <key>LANG</key>
        <string>en_US.UTF-8</string>
    </dict>
</dict>
</plist>
PLIST_EOF

echo "Wrote $PLIST"

# bootstrap does NOT reload an edited plist — you must bootout first.
launchctl bootout "gui/$UID_NUM/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$UID_NUM" "$PLIST"

# The disabled flag lives outside the plist and survives reboots and even
# deleting the plist, so clear it explicitly.
launchctl enable "gui/$UID_NUM/$LABEL"

echo
echo "Running continuously: a scan starts every 15 minutes, measured from the"
echo "start of the previous one. A scan that overruns 15 minutes is never cut"
echo "short and never skipped - the next one simply begins when it finishes."
echo
echo "  Verify it registered:  launchctl print gui/$UID_NUM/$LABEL | head -20"
echo "  Restart the loop now:  launchctl kickstart -k gui/$UID_NUM/$LABEL"
echo "  Change the cadence:    edit WATCH_INTERVAL_SECONDS in bin/loop.sh"
echo "  Watch the log:         tail -f $LOG_DIR/run.log"
echo "  Remove the schedule:   bash bin/uninstall-schedule.sh"
echo
echo "Two things worth knowing:"
echo "  • macOS will show a 'Background item added' notification. The agent also"
echo "    appears in System Settings > General > Login Items & Extensions, where"
echo "    it can be switched off — if runs stop happening, check there first."
echo "  • The loop starts its first scan immediately on load. Run the install"
echo "    while you are at the keyboard so any one-time permission prompts"
echo "    appear now rather than unattended."
